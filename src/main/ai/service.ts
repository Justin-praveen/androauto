// Generates AI test ideas for a flow and turns chosen ideas into new flows.

import type { AiSettings, AiSettingsView, Flow, TestIdeas } from '@shared/types'
import type { Store } from '../store'
import { chat, extractJson, listModels, type FetchLike } from './client'
import { applyIdea, buildPrompt, describeScreens, parseIdeas } from './testcases'

export class AiService {
  constructor(
    private readonly store: Store,
    private readonly fetchFn?: FetchLike
  ) {}

  settings(): AiSettingsView {
    const { apiKey, ...rest } = this.store.getAiSettings()
    return { ...rest, hasApiKey: !!apiKey }
  }

  saveSettings(patch: Partial<AiSettings> & { apiKey?: string }): AiSettingsView {
    this.store.saveAiSettings(patch)
    return this.settings()
  }

  models(patch?: { baseUrl?: string; apiKey?: string }): Promise<string[]> {
    const s = this.store.getAiSettings()
    return listModels({ baseUrl: patch?.baseUrl || s.baseUrl, apiKey: patch?.apiKey || s.apiKey }, this.fetchFn)
  }

  async test(): Promise<string> {
    const reply = await chat(this.store.getAiSettings(), [{ role: 'user', content: 'Reply with the single word OK.' }], this.fetchFn, 60000)
    return reply.trim().slice(0, 80)
  }

  async suggest(projectId: string, flowId: string, opts: { count: number; focus?: string }): Promise<TestIdeas> {
    const project = this.store.getProject(projectId)
    const flow = this.store.getFlow(projectId, flowId)
    const screens = describeScreens(flow, (id) => this.store.readSnapshotXml(projectId, flow, id))
    const settings = this.store.getAiSettings()
    const count = Math.min(40, Math.max(3, Math.round(opts.count) || 12))
    const reply = await chat(settings, buildPrompt(project, flow, screens, { count, focus: opts.focus?.trim() }), this.fetchFn)
    const ideas: TestIdeas = {
      flowId,
      flowVersion: flow.version,
      model: settings.model,
      generatedAt: new Date().toISOString(),
      ideas: parseIdeas(extractJson(reply), flow)
    }
    this.store.saveIdeas(projectId, ideas)
    return ideas
  }

  ideas(projectId: string, flowId: string): TestIdeas | null {
    return this.store.getIdeas(projectId, flowId)
  }

  /** Creates one flow per chosen idea, tagged "ai" and the idea's category. */
  createFlows(projectId: string, flowId: string, ideaIds: string[]): Flow[] {
    const flow = this.store.getFlow(projectId, flowId)
    const saved = this.store.getIdeas(projectId, flowId)
    if (!saved) throw new Error('Generate test ideas first')
    const taken = new Set(this.store.listFlows(projectId).map((f) => f.name.toLowerCase()))
    const created: Flow[] = []
    for (const idea of saved.ideas.filter((i) => ideaIds.includes(i.id))) {
      if (!idea.automatable) continue
      let name = `${flow.name} · ${idea.title}`.slice(0, 150)
      for (let k = 2; taken.has(name.toLowerCase()); k++) name = `${flow.name} · ${idea.title} (${k})`
      taken.add(name.toLowerCase())
      const f = this.store.createFlow(
        {
          projectId,
          name,
          description: [idea.description, idea.expected && `Expected: ${idea.expected}`, `Generated by AI from "${flow.name}"`].filter(Boolean).join('\n'),
          tags: [...new Set([...flow.tags, 'ai', idea.category])],
          recordedOn: flow.recordedOn,
          startState: flow.startState,
          variables: { ...flow.variables },
          // Snapshots stay with the original flow.
          steps: applyIdea(flow, idea).map((s) => ({ ...s, snapshot: undefined }))
        },
        new Map()
      )
      idea.createdFlowId = f.id
      created.push(f)
    }
    this.store.saveIdeas(projectId, saved)
    return created
  }
}
